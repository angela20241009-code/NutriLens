def merge_locale(en: dict, locale: dict, translations: dict) -> dict:
    merged = dict(locale)
    for key, value in en.items():
        if key.startswith("@"):
            if key[1:] in en and key not in merged:
                merged[key] = value
            continue
        if key not in merged:
            merged[key] = translations.get(key, value)
        meta_key = f"@{key}"
        if meta_key in en and meta_key not in merged:
            merged[meta_key] = en[meta_key]
    return merged


